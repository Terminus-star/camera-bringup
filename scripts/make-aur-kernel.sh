#!/usr/bin/env bash
# Generate the AUR package aur/linux-cachyos-camera/ from CachyOS's current PKGBUILD. This is the
# "version bump": run it for each new CachyOS release, test, then commit and push to the AUR.
#
#   ./scripts/make-aur-kernel.sh
#
# Same kernel as scripts/rebuild-camera-kernel.sh (CachyOS linux-cachyos-eevdf PKGBUILD with BORE,
# GCC without LTO, znver4), but the options are written into the PKGBUILD as defaults, so AUR helpers
# (paru, yay) build it the same way without any environment variables.
#
# Steps (each edit stops if the line it changes is not found exactly once):
#   1. fetch PKGBUILD + config (github.com/CachyOS/linux-cachyos, master, linux-cachyos-eevdf/)
#   2. get the kernel tarball into kernel/build/tarballs/ (kept between runs) and check its GPG signature
#   3. scripts/apply-series-to-pkgbuild.sh: no-fuzz check of kernel/patches/, overlap check,
#      _pkgsuffix=cachyos-camera, patches appended to source=() and b2sums=()
#   4. defaults _cpusched=cachyos, _processor_opt=zen4 (and check _use_llvm_lto=none);
#      depends += gz302-camera-firmware for the kernel package only; maintainer and pkgdesc lines
#   5. .SRCINFO (makepkg --printsrcinfo)
#   6. copy PKGBUILD, .SRCINFO, config and the patches into aur/linux-cachyos-camera/ (overwritten)
# Work folder: kernel/build/aur-stage.XXXXXX (new each run, git-ignored).
set -euo pipefail

project_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
variant=linux-cachyos-eevdf
raw="https://raw.githubusercontent.com/CachyOS/linux-cachyos/master/$variant"
out="$project_dir/aur/linux-cachyos-camera"
maintainer="Seifelden Abdelmonem <saif.elden.hatim@gmail.com>"

die() { echo "ERROR: $*" >&2; exit 1; }

# replace_once FILE OLD NEW: replace the line that is exactly OLD by NEW; stop unless OLD occurs once.
replace_once() {
	local n
	n=$(grep -c -x -F -- "$2" "$1" || true)
	[[ $n -eq 1 ]] || die "expected the line '$2' once in $1, found $n (CachyOS changed the PKGBUILD?)"
	OLD=$2 NEW=$3 perl -i -pe 'BEGIN { $o = $ENV{OLD}; $n = $ENV{NEW} } chomp; $_ = ($_ eq $o ? $n : $_) . "\n"' "$1"
}

# ---- 1. fetch ----
mkdir -p "$project_dir/kernel/build"
stage=$(mktemp -d -p "$project_dir/kernel/build" aur-stage.XXXXXX)
for f in PKGBUILD config; do
	curl -fsS -o "$stage/$f" "$raw/$f" || die "download failed: $raw/$f"
done
srcname=$(sed -n 's/^_srcname=//p' "$stage/PKGBUILD")
major=$(sed -n 's/^_major=//p' "$stage/PKGBUILD"); minor=$(sed -n 's/^_minor=//p' "$stage/PKGBUILD")
tagrel=$(sed -n 's/^_tagrel=//p' "$stage/PKGBUILD")
[[ $srcname == 'cachyos-${_major}.${_minor}-${_tagrel}' ]] || die "unexpected _srcname line: $srcname"
tarname="cachyos-$major.$minor-$tagrel"
echo "CachyOS $variant: $tarname"

# ---- 2. tarball (only for the patch check; the AUR package downloads it itself) ----
tars="$project_dir/kernel/build/tarballs"
mkdir -p "$tars"
url="https://github.com/CachyOS/linux/releases/download/$tarname/$tarname.tar.gz"
[[ -s $tars/$tarname.tar.gz ]] || curl -fL -o "$tars/$tarname.tar.gz" "$url" || die "download failed: $url"
[[ -s $tars/$tarname.tar.gz.asc ]] || curl -fsSL -o "$tars/$tarname.tar.gz.asc" "$url.asc" || die "download failed: $url.asc"
gpg --verify "$tars/$tarname.tar.gz.asc" "$tars/$tarname.tar.gz" || die "bad or unverifiable signature on $tarname.tar.gz"

# ---- 3. our patches and the -camera name (stops on any conflict) ----
bash "$project_dir/scripts/apply-series-to-pkgbuild.sh" "$stage" "$tars/$tarname.tar.gz"

# ---- 4. defaults, dependency, maintainer, description ----
p="$stage/PKGBUILD"
replace_once "$p" ': "${_cpusched:=eevdf}"' ': "${_cpusched:=cachyos}"	# GZ302 camera build: BORE, like linux-cachyos'
replace_once "$p" ': "${_processor_opt:=}"' ': "${_processor_opt:=zen4}"	# GZ302 camera build: like the cachyos-znver4 repo'
grep -q -x -F ': "${_use_llvm_lto:=none}"' "$p" || die "_use_llvm_lto default is no longer none"
replace_once "$p" "    depends=('coreutils' 'kmod' 'initramfs')" \
	"    depends=('coreutils' 'kmod' 'initramfs' 'gz302-camera-firmware')"
pkgdesc_line=$(grep -m1 '^pkgdesc=' "$p") || die "no pkgdesc line"
replace_once "$p" "$pkgdesc_line" \
	"pkgdesc='CachyOS kernel (BORE, GCC without LTO, znver4) with the rear camera patches for the ASUS ROG Flow Z13 GZ302'"
# Top-level depends too: makepkg only checks these before building (the ones inside _package() are
# checked by pacman at install time). Both split packages set their own depends, so the headers
# package does not inherit it.
grep -q '^depends' "$p" && die "PKGBUILD now has a top-level depends line; check the edit below by hand"
printf '\n# GZ302 camera: refuse to build without the firmware package (checked by makepkg).\ndepends+=(gz302-camera-firmware)\n' >> "$p"
# AUR convention: the new maintainer on top, earlier maintainers kept as contributors.
sed -i 's/^# Maintainer: /# Contributor: /' "$p"
sed -i "1i # Maintainer: $maintainer\\
# Based on CachyOS's linux-cachyos-eevdf PKGBUILD; generated by scripts/make-aur-kernel.sh in\\
# https://github.com/Terminus-star/camera-bringup (edit that script, not this file)." "$p"
bash -n "$p"

# ---- 5. .SRCINFO ----
# makepkg needs the PKGBUILD's folder as current directory (subshell, so this script stays put).
(cd "$stage" && makepkg --printsrcinfo > .SRCINFO)

# ---- 6. copy into aur/ ----
mkdir -p "$out"
cp "$stage/PKGBUILD" "$stage/.SRCINFO" "$stage/config" "$project_dir"/kernel/patches/*.patch "$out/"
echo "wrote $out (from $stage)"
